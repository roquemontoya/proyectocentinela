insert into public.app_role_permissions (role_id, permission_id)
select r.id, p.id
from public.app_roles r
join public.app_permissions p on p.permission_key in (
  'activos.read','controles.read','controles.create','anomalias.read','anomalias.create','pulmon.read','personal.read'
)
where r.role_key = 'bomberos'
on conflict do nothing;

insert into public.app_role_permissions (role_id, permission_id)
select r.id, p.id
from public.app_roles r
cross join public.app_permissions p
where r.role_key = 'administrador'
  and p.permission_key <> 'roles.manage'
on conflict do nothing;

insert into public.app_role_permissions (role_id, permission_id)
select r.id, p.id
from public.app_roles r
cross join public.app_permissions p
where r.role_key = 'superadministrador'
on conflict do nothing;

create or replace function public.current_user_has_role(p_role text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.app_user_roles ur
    join public.app_roles r on r.id = ur.role_id
    where ur.user_id = (select auth.uid())
      and r.role_key = p_role
  );
$$;

revoke all on function public.current_user_has_role(text) from public;
revoke all on function public.current_user_has_role(text) from anon;
grant execute on function public.current_user_has_role(text) to authenticated;

