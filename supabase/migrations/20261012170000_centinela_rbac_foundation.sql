-- Proyecto Centinela 2.0: base extensible de roles y permisos.
-- Esta migración es aditiva: no cambia aún las políticas de las tablas operativas.
create table if not exists public.app_roles (
  id bigint generated by default as identity primary key,
  role_key text not null unique,
  nombre text not null,
  descripcion text,
  created_at timestamptz not null default now(),
  constraint app_roles_role_key_format check (role_key ~ '^[a-z][a-z0-9_]*$')
);

create table if not exists public.app_permissions (
  id bigint generated by default as identity primary key,
  permission_key text not null unique,
  descripcion text,
  created_at timestamptz not null default now(),
  constraint app_permissions_key_format check (permission_key ~ '^[a-z][a-z0-9_.]*$')
);

create table if not exists public.app_role_permissions (
  role_id bigint not null references public.app_roles(id) on delete cascade,
  permission_id bigint not null references public.app_permissions(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (role_id, permission_id)
);

create table if not exists public.app_user_roles (
  user_id uuid not null references auth.users(id) on delete cascade,
  role_id bigint not null references public.app_roles(id) on delete cascade,
  assigned_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (user_id, role_id)
);

create index if not exists app_user_roles_role_id_idx on public.app_user_roles(role_id);
create index if not exists app_role_permissions_permission_id_idx on public.app_role_permissions(permission_id);

